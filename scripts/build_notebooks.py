#!/usr/bin/env python3
"""Generate the Fabric notebooks in notebooks/ from the engine in src/medallion/.

Each notebook is self-contained: the engine modules it needs are copied into its code cells,
so Fabric needs nothing installed beyond Polars, deltalake (and DuckDB for gold). The
parameter cell is generated from the layer's Params class, so the notebook, the CLI and
pipelines all share one list of parameters and defaults.

The layout of each notebook (markdown, and where the parameter, engine and run cells go)
is in scripts/notebook_templates/<notebook>.txt. Cells there start with a marker line:

    #%% markdown                 a markdown cell
    #%% code                     a code cell, copied as is
    #%% parameters <module>.<Class>   the parameter cell, generated from a Params dataclass
    #%% engine <module>          a code cell holding src/medallion/<module>.py

Usage:
    python scripts/build_notebooks.py           # write notebooks/*.ipynb
    python scripts/build_notebooks.py --check   # fail if any notebook is out of date (CI)
"""
import argparse
import dataclasses
import importlib
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "src"
TEMPLATES = Path(__file__).resolve().parent / "notebook_templates"
OUT = REPO / "notebooks"
NOTEBOOKS = ["feed_loader", "bronze_to_silver", "silver_to_gold"]

METADATA = {"kernelspec": {"name": "jupyter", "display_name": "Jupyter"},
            "language_info": {"name": "python"}}

# relative imports between engine modules: dropped, because the notebook is one namespace
RELATIVE_IMPORT = re.compile(r"^from \.\w* import (\([^)]*\)|[^\n]*)\n", re.M)


def engine_cell(module):
    path = SRC / "medallion" / f"{module}.py"
    code = RELATIVE_IMPORT.sub("", path.read_text(encoding="utf-8"))
    header = (f"# ---- Engine: src/medallion/{module}.py -------------------------------------------\n"
              f"# Generated by scripts/build_notebooks.py. Change the file in the repo, not this cell.\n")
    return header + code.strip() + "\n"


def py_literal(v):
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, bool) or v is None:
        return repr(v)
    if isinstance(v, int) and abs(v) >= 10_000:
        return f"{v:_}"
    return repr(v)


def parameters_cell(spec):
    module, cls_name = spec.rsplit(".", 1)
    sys.path.insert(0, str(SRC))
    try:
        cls = getattr(importlib.import_module(f"medallion.{module}"), cls_name)
    finally:
        sys.path.pop(0)
    rows = [(f.name, py_literal(f.default), f.metadata.get("help", "")) for f in dataclasses.fields(cls)]
    w_name = max(len(n) for n, _, _ in rows)
    w_val = max(len(v) for _, v, h in rows if h)
    lines = ["# Parameters (mark this cell as a parameter cell so a pipeline can override)"]
    for name, value, help_ in rows:
        line = f"{name:<{w_name}} = {value}"
        if help_:
            line = f"{line:<{w_name + 3 + w_val}}  # {help_}"
        lines.append(line)
    return "\n".join(lines)


def parse_template(text):
    """Template text -> list of (kind, argument, body)."""
    cells, cur = [], None
    for line in text.splitlines():
        m = re.match(r"^#%%\s+(\w+)\s*(.*?)\s*$", line)
        if m:
            cur = [m.group(1), m.group(2), []]
            cells.append(cur)
        elif cur is None:
            if line.strip():
                raise ValueError(f"text before the first #%% marker: {line!r}")
        else:
            cur[2].append(line)
    return [(k, a, "\n".join(b).strip("\n")) for k, a, b in cells]


def build(name):
    cells = []
    for kind, arg, body in parse_template((TEMPLATES / f"{name}.txt").read_text(encoding="utf-8")):
        if kind == "markdown":
            cells.append({"cell_type": "markdown", "metadata": {}, "source": body})
            continue
        if kind == "code":
            source, meta = body, {}
        elif kind == "parameters":
            source, meta = parameters_cell(arg), {"tags": ["parameters"]}
        elif kind == "engine":
            source, meta = engine_cell(arg), {}
        else:
            raise ValueError(f"{name}.txt: unknown cell kind '{kind}'")
        cells.append({"cell_type": "code", "metadata": meta, "execution_count": None,
                      "outputs": [], "source": source})
    nb = {"cells": cells, "metadata": METADATA, "nbformat": 4, "nbformat_minor": 5}
    return json.dumps(nb, indent=1, ensure_ascii=True) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="Fail if a notebook differs from what would be generated")
    args = ap.parse_args()
    stale = []
    for name in NOTEBOOKS:
        text = build(name)
        path = OUT / f"{name}.ipynb"
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            print(f"{path.relative_to(REPO).as_posix()}: up to date")
        elif args.check:
            stale.append(name)
            print(f"{path.relative_to(REPO).as_posix()}: OUT OF DATE")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"{path.relative_to(REPO).as_posix()}: written")
    if stale:
        sys.exit("Notebooks are out of date with src/medallion. Run: python scripts/build_notebooks.py")


if __name__ == "__main__":
    main()
